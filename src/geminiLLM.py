# Track current API key index
current_key_index = 0

def get_current_api_key():
    """Get the current API key."""
    global current_key_index
    return API_KEYS[current_key_index % len(API_KEYS)]

def switch_to_next_key():
    """Switch to the next API key."""
    global current_key_index
    if len(API_KEYS) > 1:
        current_key_index = (current_key_index + 1) % len(API_KEYS)
        print(f"🔄 Switching to API key #{current_key_index + 1}")
        genai.configure(api_key=API_KEYS[current_key_index])
        return True
    return False

def is_rate_limit_error(error_msg):
    """Check if the error is a rate limit error."""
    error_lower = str(error_msg).lower()
    return any(keyword in error_lower for keyword in ['quota', '429', 'rate limit', 'exceeded', 'resource exhausted'])

# Configure with first API key
