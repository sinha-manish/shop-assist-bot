# The system instruction is part of the model's configuration.
SYSTEM_INSTRUCTION = (
    "You are a friendly and professional store assistant for Shop Assist. "
    "CRITICAL: You MUST ONLY use information provided in the 'Retrieved Information' section. "
    "DO NOT make up, infer, or assume any information that is not explicitly provided. "
    "If information is missing, state 'Information not available' rather than guessing. "
    "Always cite specific product names, store names, and locations from the provided data. "
    "Speak naturally like a real store employee - use phrases like 'we have', 'available in our store', 'in stock', etc. "
    "NEVER use technical terms like 'database', 'matching products', 'search results', 'retrieved information', etc. "
    "Keep responses concise, friendly, and professional - like you're helping a customer in the store. "
    "Do not use emojis or excessive punctuation."
)

def generate_human_readable_response(user_question, structured_data, conversation_context=None):
    """
    Calls the Gemini API to convert structured data into a human-readable response.

    Args:
        user_question (str): The original question from the user.
        structured_data (str): The structured data returned from your system.
        conversation_context (str, optional): Previous conversation history for context-aware responses.

    Returns:
        str: A natural, conversational response generated by the Gemini model.
    """
    print(f"Generating response for question: {user_question}")
    if conversation_context:
        print(f"Using conversation context: {conversation_context[:100]}...")
    print(f"Using structured data: {structured_data[:200]}...")
    try:
        # Initialize the model (system_instruction parameter not supported in v0.3.2)
        # Include system instruction in the prompt instead
        model = genai.GenerativeModel('gemini-2.5-flash-lite')

        # Build prompt with optional conversation context
        context_section = ""
        if conversation_context:
            context_section = (
                f"\n\nPrevious Conversation Context:\n"
                f"{conversation_context}\n"
                f"\nNote: This is a continuation of the previous conversation. "
                f"Use the context to provide relevant follow-up information and maintain conversation flow.\n"
            )

        # Include system instruction at the start of the prompt
        prompt_text = (
            f"System Instructions:\n"
            f"{SYSTEM_INSTRUCTION}\n\n"
            f"Customer Question: '{user_question}'{context_section}\n\n"
            f"Available Products in Our Store:\n"
            f"{structured_data}\n\n"
            "CRITICAL INSTRUCTIONS:\n"
            "- You MUST ONLY use information from the 'Available Products' section above\n"
            "- DO NOT add, infer, or make up any information not explicitly provided\n"
            "- If a field is missing or shows 'None', state 'Information not available' - do not guess\n"
            "- Always cite specific product names, store names, and exact values from the data\n"
            "- Speak naturally like a store assistant - NEVER use technical terms like 'database', 'matching products', 'search results', 'found in database', etc.\n"
            "- Use natural store language: 'we have', 'available in our store', 'in stock', 'at our location', etc.\n"
            "- Provide a friendly, professional answer like you're helping a customer in person\n"
        )
        
        # Add context-aware instructions if this is a continuation
        if conversation_context:
            prompt_text += (
                "- This is a continuation of a conversation. Reference previous messages naturally if relevant\n"
                "- If the user is asking for more information about previously mentioned products, provide additional details\n"
                "- Maintain conversational flow and coherence with previous messages\n"
            )
        
        prompt_text += (
            "- The customer will see product cards with images showing all product details (name, description, category, size, color, material, price, availability, store location)\n"
            "- Your response should be a natural, friendly summary like a store assistant would give\n"
            "- DO NOT repeat all the product details - the cards already show them\n"
            "- Instead, provide a brief, friendly summary like:\n"
            "  * Acknowledge what the customer is looking for\n"
            "  * Mention what you have available (e.g., 'We have 3 options for you', 'I found a great option', 'We have several styles available')\n"
            "  * Highlight key points naturally (e.g., 'Available in multiple sizes', 'Great discounts on these', 'In stock at our Hyderabad store')\n"
            "  * Keep it concise (2-3 sentences maximum)\n"
            "- If multiple products are available, mention the variety naturally (e.g., 'We have several options in different colors and sizes', 'You'll find a nice selection below')\n"
            "- If no items are found, say something friendly and specific like 'I'm sorry, we don't currently have [specific item] in stock' (e.g., 'we don't have green shirts for men in stock right now')\n"
            "- Be specific about what wasn't found - mention the exact item requested (color, type, gender if specified)\n"
            "- NEVER say 'found in database', 'matching products', 'search results', or any technical terms\n"
            "- Use natural phrases: 'we have', 'available', 'in stock', 'at our store', 'you can see', etc.\n"
            "- Be friendly, professional, and helpful - like you're talking to a customer in the store\n"
            "- Do not use emojis, excessive punctuation, or overly enthusiastic language\n"
            "- Let the product cards show the details - your job is just to give a friendly introduction"
        )
        
        # Now, call generate_content with timeout and generation config for faster responses
        import time
        gemini_start = time.time()
        
        # Generation config for faster, more concise responses
        generation_config = {
            "temperature": 0.7,
            "top_p": 0.8,
            "top_k": 40,
            "max_output_tokens": 1024,  # Increased to allow complete responses
        }
        
        try:
            response = model.generate_content(
                contents=[{"role": "user", "parts": [{"text": prompt_text}]}],
                generation_config=generation_config
            )
            gemini_time = time.time() - gemini_start
            if gemini_time > 5.0:
                print(f"⚠️ Gemini API call took {gemini_time:.2f}s (slow)")
            
            # Check if response was blocked or filtered
            if not response.candidates or len(response.candidates) == 0:
                print("⚠️ Gemini API: No candidates returned (content may be filtered)")
                # Fallback: return a simple response based on structured data
                if "No matching items" in structured_data or "not found" in structured_data.lower():
                    return "I'm sorry, we don't currently have that item in stock. Please try searching for something else."
                else:
                    return "I found some products for you. Please check the product cards below for details."
            
            # Check finish reason - finish_reason 2 = SAFETY (blocked by safety filters)
            candidate = response.candidates[0]
            finish_reason = getattr(candidate, 'finish_reason', None)
            
            # Handle blocked responses
            # finish_reason can be an integer (2 = SAFETY) or enum/string
            # Check for blocked responses (anything other than STOP/SUCCESS)
            is_blocked = False
            finish_reason_str = str(finish_reason) if finish_reason is not None else "None"
            
            is_max_tokens = False
            if finish_reason is not None:
                # Check if it's an integer (2 = SAFETY, 1 = STOP, 5 = MAX_TOKENS)
                if isinstance(finish_reason, int):
                    is_blocked = finish_reason not in [1, 5]  # 1 = STOP (success), 5 = MAX_TOKENS (truncated but ok)
                    is_max_tokens = finish_reason == 5
                    finish_reason_names = {1: "STOP", 2: "SAFETY", 3: "RECITATION", 4: "OTHER", 5: "MAX_TOKENS"}
                    finish_reason_str = finish_reason_names.get(finish_reason, f"UNKNOWN({finish_reason})")
                # Check if it's a string/enum
                elif isinstance(finish_reason, str):
                    is_blocked = finish_reason.upper() not in ['STOP', 'FINISH_REASON_UNSPECIFIED', 'MAX_TOKENS']
                    is_max_tokens = finish_reason.upper() == 'MAX_TOKENS'
                    finish_reason_str = finish_reason
                # Check if it's an enum object
                elif hasattr(finish_reason, 'name'):
                    is_blocked = finish_reason.name.upper() not in ['STOP', 'FINISH_REASON_UNSPECIFIED', 'MAX_TOKENS']
                    is_max_tokens = finish_reason.name.upper() == 'MAX_TOKENS'
                    finish_reason_str = finish_reason.name
                elif hasattr(finish_reason, 'value'):
                    # Enum with value attribute
                    finish_reason_value = finish_reason.value
                    if isinstance(finish_reason_value, int):
                        is_blocked = finish_reason_value not in [1, 5]
                        is_max_tokens = finish_reason_value == 5
                    finish_reason_str = str(finish_reason)
            
            if is_blocked:
                print(f"⚠️ Gemini API: Response blocked (finish_reason: {finish_reason_str})")
                
                # Try to extract text from parts if available (sometimes partial text exists)
                if hasattr(candidate, 'content') and hasattr(candidate.content, 'parts'):
                    parts_text = []
                    for part in candidate.content.parts:
                        if hasattr(part, 'text') and part.text:
                            parts_text.append(part.text)
                    if parts_text:
                        return ' '.join(parts_text)
                
                # Fallback: return a simple response based on structured data
                if "No matching items" in structured_data or "not found" in structured_data.lower():
                    return "I'm sorry, we don't currently have that item in stock. Please try searching for something else."
                else:
                    return "I found some products for you. Please check the product cards below for details."
            
            # Try to get response text
            try:
                response_text = response.text
                
                # If response was truncated due to max tokens, clean up the ending
                if is_max_tokens:
                    print(f"⚠️ Response truncated (MAX_TOKENS). Cleaning up ending...")
                    # Try to end at the last complete sentence
                    last_period = response_text.rfind('.')
                    last_exclaim = response_text.rfind('!')
                    last_question = response_text.rfind('?')
                    last_sentence_end = max(last_period, last_exclaim, last_question)
                    
                    if last_sentence_end > len(response_text) * 0.5:  # At least half the response
                        response_text = response_text[:last_sentence_end + 1]
                    else:
                        # Just add ellipsis if we can't find a good ending
                        response_text = response_text.rstrip() + "..."
                
                print(f"Response generated successfully. {response_text[:100]}...")
                return response_text
            except Exception as text_error:
                print(f"⚠️ Error accessing response.text: {text_error}")
                print(f"   Finish reason: {finish_reason}")
                print(f"   Candidates: {len(response.candidates) if response.candidates else 0}")
                
                # Fallback: try to extract text from parts
                if response.candidates and len(response.candidates) > 0:
                    candidate = response.candidates[0]
                    if hasattr(candidate, 'content') and hasattr(candidate.content, 'parts'):
                        parts_text = []
                        for part in candidate.content.parts:
                            if hasattr(part, 'text') and part.text:
                                parts_text.append(part.text)
                        if parts_text:
                            return ' '.join(parts_text)
                
                # Last resort: return fallback based on structured data
                if "No matching items" in structured_data or "not found" in structured_data.lower():
                    return "I'm sorry, we don't currently have that item in stock. Please try searching for something else."
                else:
                    return "I found some products for you. Please check the product cards below for details."
                    
        except Exception as e:
            gemini_time = time.time() - gemini_start
            error_msg = str(e)
            print(f"❌ Gemini API error: {error_msg}")
            
            # Check if we have products to show (structured_data has items)
            has_products = structured_data and "items available" in structured_data.lower() and "No matching items" not in structured_data
            
            if "timeout" in error_msg.lower() or gemini_time > 30:
                print(f"❌ Gemini API timeout after {gemini_time:.2f}s")
                if has_products:
                    return "I found some products for you! Please check the product cards below for details."
                return "I'm sorry, the response is taking longer than expected. Please try again with a simpler query."
            elif is_rate_limit_error(error_msg):
                print("⚠️ Gemini API: Quota exceeded or rate limited")
                
                # Try all remaining API keys
                keys_tried = 1  # Already tried the first key
                max_retries = len(API_KEYS) - 1  # Remaining keys to try
                
                while keys_tried <= max_retries:
                    if switch_to_next_key():
                        print(f"🔄 Retrying with API key #{current_key_index + 1} (attempt {keys_tried + 1}/{len(API_KEYS)})...")
                        try:
                            # Retry the API call with new key
                            model = genai.GenerativeModel('gemini-2.5-flash-lite')
                            
                            # Rebuild the prompt
                            context_section = ""
                            if conversation_context:
                                context_section = (
                                    f"\n\nPrevious Conversation Context:\n"
                                    f"{conversation_context}\n"
                                    f"\nNote: This is a continuation of the previous conversation.\n"
                                )
                            
                            retry_prompt = (
                                f"System Instructions:\n{SYSTEM_INSTRUCTION}\n\n"
                                f"Customer Question: '{user_question}'{context_section}\n\n"
                                f"Available Products in Our Store:\n{structured_data}\n\n"
                                "Provide a friendly, professional response like a store assistant."
                            )
                            
                            retry_response = model.generate_content(
                                retry_prompt,
                                generation_config=types.GenerationConfig(
                                    temperature=0.7,
                                    max_output_tokens=500,
                                ),
                                safety_settings={
                                    'HARM_CATEGORY_HARASSMENT': 'BLOCK_NONE',
                                    'HARM_CATEGORY_HATE_SPEECH': 'BLOCK_NONE',
                                    'HARM_CATEGORY_SEXUALLY_EXPLICIT': 'BLOCK_NONE',
                                    'HARM_CATEGORY_DANGEROUS_CONTENT': 'BLOCK_NONE',
                                }
                            )
                            
                            if retry_response and retry_response.text:
                                print(f"✅ Retry successful with API key #{current_key_index + 1}!")
                                return retry_response.text
                        except Exception as retry_error:
                            retry_error_msg = str(retry_error)
                            print(f"❌ API key #{current_key_index + 1} also failed: {retry_error_msg[:100]}")
                            
                            # If this key also hit rate limit, try next key
                            if is_rate_limit_error(retry_error_msg):
                                keys_tried += 1
                                continue
                            else:
                                # Non-rate-limit error, stop retrying
                                break
                    else:
                        break
                    keys_tried += 1
                
                print(f"❌ All {len(API_KEYS)} API keys exhausted or failed")
                
                # If all retries failed, return fallback
                if has_products:
                    return "Here are the products I found for you! Check out the options below."
                return "I'm currently experiencing high demand. Please try again in a moment."
            elif "finish_reason" in error_msg.lower() or "blocked" in error_msg.lower() or "safety" in error_msg.lower():
                print("⚠️ Gemini API: Response was blocked by safety filters")
                # Fallback response
                if "No matching items" in structured_data or "not found" in structured_data.lower():
                    return "I'm sorry, we don't currently have that item in stock. Please try searching for something else."
                else:
                    return "I found some products for you. Please check the product cards below for details."
            else:
                # Other error - check if we have products to show
                if has_products:
                    return "I found some products matching your search! Take a look at the options below."
                return "I'm sorry, I encountered an issue processing your request. Please try again."

    except Exception as e:
        print(f"An error occurred: {e}")
        return "Sorry, I am unable to process that request at the moment. Please try again later."

